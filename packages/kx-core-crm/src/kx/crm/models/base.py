"""Declarative base for the `crm` schema and the column shorthands every model uses.

The DDL in db/ddl/01_crm.sql is the source of truth; these mappings mirror it column for column
(tests/test_models_ddl.py compares them against information_schema). Defaults computed by the
database (now(), sequences, gen_random_uuid) are marked `FetchedValue` so the ORM reads them back
with RETURNING instead of guessing them in Python.
"""

from __future__ import annotations

import uuid
from datetime import datetime
from typing import TYPE_CHECKING, Any, Final

from sqlalchemy import DateTime, FetchedValue, ForeignKey, Numeric
from sqlalchemy.orm import DeclarativeBase, Mapped, mapped_column

from kx.core.db import make_base
from kx.core.identity import new_id

SCHEMA: Final = "crm"

if TYPE_CHECKING:

    class Base(DeclarativeBase):
        """Static stand-in for mypy: `make_base` builds the real class at runtime."""
else:
    Base = make_base(SCHEMA)

DB_DEFAULT: Final = FetchedValue()

# numeric(14,4) money and numeric(14,6) per-piece prices, always Decimal (never float)
Money = Numeric(14, 4, asdecimal=True)
UnitPrice = Numeric(14, 6, asdecimal=True)
Pct = Numeric(6, 2, asdecimal=True)
TZ = DateTime(timezone=True)


def uuid_pk() -> Mapped[uuid.UUID]:
    """UUIDv7 primary key generated by the app (index-friendly, time ordered)."""
    return mapped_column(primary_key=True, default=new_id)


def created_at() -> Mapped[datetime]:
    return mapped_column(TZ, server_default=DB_DEFAULT)


def updated_at() -> Mapped[datetime]:
    """Maintained by the crm.touch_updated_at trigger; read back after every UPDATE."""
    return mapped_column(TZ, server_default=DB_DEFAULT, server_onupdate=DB_DEFAULT)


def ref(column: str, **kw: Any) -> ForeignKey:
    """ForeignKey shorthand inside the crm schema."""
    return ForeignKey(f"{SCHEMA}.{column}", **kw)


# Tables with an updated_at trigger need RETURNING on UPDATE too.
TOUCHED: Final[dict[str, Any]] = {"eager_defaults": True}

__all__ = [
    "DB_DEFAULT",
    "SCHEMA",
    "TOUCHED",
    "TZ",
    "Base",
    "Money",
    "Pct",
    "UnitPrice",
    "created_at",
    "ref",
    "updated_at",
    "uuid_pk",
]
